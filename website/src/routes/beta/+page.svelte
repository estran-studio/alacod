	<span class="eyebrow">GUIDE BÊTA</span>
	<h1>Venez jouer.<br /><span>Dites-nous ce qui coince.</span></h1>
	<p>Les premières sessions servent à tester les jeux avec des amis, sur de vraies machines et de vrais réseaux.</p>
</section>
<section class="section-wrap prose">
	<h2>Pour commencer</h2>
	<ol class="steps">
		<li>Ouvrez le catalogue sur un ordinateur avec clavier et souris. Commencez par Chrome ou Firefox à jour.</li>
		<li>Choisissez un jeu dont la version solo est publiée. Les contrôles et la version apparaissent avant le lancement.</li>
		<li>Pour une partie en ligne, utilisez le lien d’invitation partagé par votre ami lorsque ce mode est disponible.</li>
	</ol>
	<h2>À essayer</h2>
	<p>
		Le chargement, les contrôles, le ressenti des armes, la lisibilité du HUD, les achats ou mutations et la relance après une défaite. En
		coopération, vérifiez aussi l’attente au salon et la réanimation.
	</p>
	<h2>Si quelque chose ne marche pas</h2>
	<p>
		Notez le jeu, la version affichée, votre navigateur et votre système, le nombre de joueurs, ce que vous faisiez et le résultat attendu.
		Une capture ou les logs du jeu peuvent aider. Retirez les liens privés et les tokens avant de les partager.
	</p>
	<a class="button primary" href="https://github.com/bascanada/alacod/issues/new">Ouvrir un rapport ↗</a>
	<h2>Limites actuelles</h2>
	<p>
		La bêta web se prépare. Mobile, manette, reconnexion en pleine partie et Safari ne sont pas encore annoncés comme validés. Les boutons
		de jeu reflètent les builds publiés, pas seulement l’état du code natif.
	</p>
</section>
